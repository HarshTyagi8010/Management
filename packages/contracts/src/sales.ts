import { z } from 'zod';
import { documentArtifactSchema, lineDiscountSchema } from './finance.js';
import { stateCodeSchema } from './india.js';
import { addressSchema } from './organization.js';
import { patchShape } from './patch.js';
import { businessDateSchema, moneySchema, nonNegativeMoneySchema, objectIdSchema, quantitySchema, unitPriceSchema } from './primitives.js';

/**
 * Order to cash (FR-SAL-01..09, workflows.md §1–4): quotations and proforma
 * invoices, sales orders with stock reservations, dispatches (delivery
 * challans), tax invoices and bills of supply, and receivables.
 *
 * Every figure is computed on the server with the Phase 6 calculation; issued
 * documents keep the figures and the seller, buyer and item details they were
 * issued with (snapshots), and are never recomputed. Prices and amounts are
 * omitted for callers who only move goods (e.g. a storekeeper reading a
 * dispatch); costs are omitted without price.view_cost (FR-RBAC-04).
 */

const version = z.number().int().min(0);
const positiveQuantity = quantitySchema.refine((v) => !v.startsWith('-') && /[1-9]/.test(v), 'Enter a quantity more than zero');
/** Line ids are 12 hex characters, generated by the server. */
export const lineIdSchema = z.string().regex(/^[0-9a-f]{12}$/, 'Unknown line');
const partyAddressId = z.string().regex(/^[A-Za-z0-9_-]{1,24}$/);

export const SALES_DOC_TYPES = ['quotation', 'sales_order', 'dispatch', 'sales_invoice'] as const;
export type SalesDocType = (typeof SALES_DOC_TYPES)[number];

export const QUOTATION_STATUSES = ['draft', 'sent', 'accepted', 'rejected', 'expired', 'revised', 'converted', 'discarded'] as const;
export const SALES_ORDER_STATUSES = ['draft', 'confirmed', 'partially_fulfilled', 'fulfilled', 'closed', 'cancelled', 'discarded'] as const;
export const DISPATCH_STATUSES = ['draft', 'dispatched', 'partially_invoiced', 'invoiced', 'cancelled', 'discarded'] as const;
export const SALES_INVOICE_STATUSES = ['draft', 'issued', 'cancelled', 'discarded'] as const;
export type QuotationStatus = (typeof QUOTATION_STATUSES)[number];
export type SalesOrderStatus = (typeof SALES_ORDER_STATUSES)[number];
export type DispatchStatus = (typeof DISPATCH_STATUSES)[number];
export type SalesInvoiceStatus = (typeof SALES_INVOICE_STATUSES)[number];
export type SalesDocStatus = QuotationStatus | SalesOrderStatus | DispatchStatus | SalesInvoiceStatus;

export const SALES_STATUS_LABELS: Record<SalesDocStatus, string> = {
  draft: 'Draft',
  sent: 'Sent',
  accepted: 'Accepted',
  rejected: 'Rejected',
  expired: 'Expired',
  revised: 'Revised',
  converted: 'Converted',
  discarded: 'Discarded',
  confirmed: 'Confirmed',
  partially_fulfilled: 'Partly fulfilled',
  fulfilled: 'Fulfilled',
  closed: 'Closed',
  cancelled: 'Cancelled',
  dispatched: 'Dispatched',
  partially_invoiced: 'Partly invoiced',
  invoiced: 'Invoiced',
  issued: 'Issued',
};

/** Derived from receipts allocated to the invoice (Phase 9); every issued invoice is unpaid until then. */
export const PAYMENT_STATUSES = ['unpaid', 'partially_paid', 'paid'] as const;
/** Regulatory sub-state (gst.md §5). This system submits nothing to the IRP; "not submitted" is shown where e-invoicing applies. */
export const EINVOICE_STATUSES = ['not_applicable', 'not_submitted'] as const;

/**
 * The document type that numbers the document (organization DOCUMENT_TYPES):
 * a quotation or proforma, a sales order, a delivery challan, and a tax invoice
 * or bill of supply (decided by the seller's registration and the lines: GST-14).
 */
export const SALES_DOCUMENT_KINDS = ['quotation', 'proforma_invoice', 'sales_order', 'delivery_challan', 'tax_invoice', 'bill_of_supply'] as const;
export type SalesDocumentKind = (typeof SALES_DOCUMENT_KINDS)[number];

// ----------------------------------------------------------------- input

export const salesLineInputSchema = z.strictObject({
  itemId: objectIdSchema,
  qty: positiveQuantity,
  unitPrice: unitPriceSchema,
  discount: lineDiscountSchema.default(null),
  /** On a document made from another one: the order or dispatch line it fulfils or bills. */
  sourceLineId: lineIdSchema.nullable().default(null),
});

const docFields = {
  legalEntityId: objectIdSchema,
  /** The seller's GSTIN (place of business). */
  gstRegistrationId: objectIdSchema,
  partyId: objectIdSchema,
  docDate: businessDateSchema,
  /** Ids of the customer's addresses (party addresses). */
  billingAddressId: partyAddressId.nullable().default(null),
  shippingAddressId: partyAddressId.nullable().default(null),
  /**
   * null: taken from the shipping address, else the billing address (GST-10, legal review C-01).
   * A state chosen here that differs from that default is an override, recorded in the audit log.
   */
  placeOfSupply: stateCodeSchema.nullable().default(null),
  documentDiscount: nonNegativeMoneySchema.default('0'),
  /** The customer's PO number or similar. */
  customerReference: z.string().trim().max(60).default(''),
  notes: z.string().trim().max(1000).default(''),
  terms: z.string().trim().max(2000).default(''),
  /** Numbering series; null = the default series of the document type. */
  seriesId: objectIdSchema.nullable().default(null),
  lines: z.array(salesLineInputSchema).min(1, 'Add at least one line').max(200),
};

const validDates = <T extends { docDate?: string | undefined; validUntil?: string | null | undefined; dueDate?: string | null | undefined; expectedDate?: string | null | undefined }>(v: T, ctx: z.RefinementCtx) => {
  for (const key of ['validUntil', 'dueDate', 'expectedDate'] as const) {
    const value = v[key];
    if (value && v.docDate && value < v.docDate) ctx.addIssue({ code: 'custom', path: [key], message: 'This date can’t be before the document date' });
  }
};

const quotationFields = {
  ...docFields,
  /** A proforma invoice is a quotation-like document asking for payment; neither is a tax invoice (FR-SAL-02). */
  kind: z.enum(['quotation', 'proforma']).default('quotation'),
  validUntil: businessDateSchema.nullable().default(null),
};
export const quotationInputSchema = z.strictObject(quotationFields).superRefine(validDates);
export const quotationUpdateSchema = z.strictObject({ ...patchShape(z.strictObject(quotationFields).omit({ legalEntityId: true, kind: true }).shape), version }).superRefine(validDates);

const orderFields = {
  ...docFields,
  /** Where the goods are reserved and leave from; needed to confirm an order with stock items. */
  warehouseId: objectIdSchema.nullable().default(null),
  expectedDate: businessDateSchema.nullable().default(null),
};
export const salesOrderInputSchema = z.strictObject(orderFields).superRefine(validDates);
export const salesOrderUpdateSchema = z.strictObject({ ...patchShape(z.strictObject(orderFields).omit({ legalEntityId: true }).shape), version }).superRefine(validDates);

/** Recorded for the delivery challan; e-way bills are not generated by this system (GST-20). */
export const transportSchema = z.strictObject({
  vehicleNumber: z.string().trim().toUpperCase().max(20).default(''),
  transporterName: z.string().trim().max(80).default(''),
  ewayBillNumber: z.union([z.literal(''), z.string().regex(/^\d{12}$/, 'An e-way bill number has 12 digits')]).default(''),
});
export type Transport = z.infer<typeof transportSchema>;

/**
 * Dispatch lines may leave out the price: people who only move goods don't see
 * prices. The server then takes it from the order line, the draft's own line,
 * or the item's sale price.
 */
export const dispatchLineInputSchema = z.strictObject({
  itemId: objectIdSchema,
  qty: positiveQuantity,
  unitPrice: unitPriceSchema.optional(),
  discount: lineDiscountSchema.optional(),
  sourceLineId: lineIdSchema.nullable().default(null),
});

const dispatchFields = {
  ...docFields,
  lines: z.array(dispatchLineInputSchema).min(1, 'Add at least one line').max(200),
  warehouseId: objectIdSchema,
  transport: transportSchema.default({ vehicleNumber: '', transporterName: '', ewayBillNumber: '' }),
};
export const dispatchInputSchema = z.strictObject(dispatchFields);
export const dispatchUpdateSchema = z.strictObject({ ...patchShape(z.strictObject(dispatchFields).omit({ legalEntityId: true }).shape), version });

const invoiceFields = {
  ...docFields,
  /** Where stock leaves from when the stock-out point is the invoice. */
  warehouseId: objectIdSchema.nullable().default(null),
  /** null: document date plus the customer's payment terms. */
  dueDate: businessDateSchema.nullable().default(null),
};
export const salesInvoiceInputSchema = z.strictObject(invoiceFields).superRefine(validDates);
export const salesInvoiceUpdateSchema = z.strictObject({ ...patchShape(z.strictObject(invoiceFields).omit({ legalEntityId: true }).shape), version }).superRefine(validDates);

// -------------------------------------------------------------- commands

export const salesCommandSchema = z.strictObject({ version });
export const reasonCommandSchema = z.strictObject({ version, reason: z.string().trim().min(5, 'Say why (for the audit log)').max(300) });
export const quotationConvertSchema = z.strictObject({ version, to: z.enum(['sales_order', 'sales_invoice']) });
/** Confirming an order or issuing an invoice beyond the customer's credit limit needs credit.override (FR-SAL-08). */
export const orderConfirmSchema = z.strictObject({ version, overrideCreditLimit: z.boolean().default(false) });
export const invoiceIssueSchema = z.strictObject({
  version,
  /** The grand total the user saw. If rates or masters changed since, the issue is refused for review. */
  expectedTotal: moneySchema.optional(),
  overrideCreditLimit: z.boolean().default(false),
});

