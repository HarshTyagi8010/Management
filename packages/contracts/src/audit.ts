export type AuditAction = (typeof AUDIT_ACTIONS)[number];

/** A changed field. Values are included only for non-personal fields (role names, statuses, permissions). */
export const auditChangeSchema = z.strictObject({
  field: z.string(),
  from: z.unknown().optional(),
  to: z.unknown().optional(),
});

export const auditEventSchema = z.strictObject({
  id: objectIdSchema,
  at: z.iso.datetime(),
  action: z.enum(AUDIT_ACTIONS),
  actor: z.strictObject({ id: objectIdSchema, name: z.string() }).nullable(),
  entityType: z.string(),
  entityId: z.string().nullable(),
  summary: z.string(),
  changes: z.array(auditChangeSchema),
  requestId: z.string(),
});

export const auditListQuerySchema = z.strictObject({
  limit: z.coerce.number().int().min(1).max(100).default(50),
  cursor: objectIdSchema.optional(),
  action: z.enum(AUDIT_ACTIONS).optional(),
});

export type AuditEvent = z.infer<typeof auditEventSchema>;
export type AuditChange = z.infer<typeof auditChangeSchema>;
