import AxeBuilder from '@axe-core/playwright';
import { expect, test } from './fixtures';

const WCAG_TAGS = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'];
const AXE_TIMEOUT = 90_000;

/** Phase 7 screens with the text that shows their data has loaded. */
const pages = () =>
  [
    ['quotations', '/sales/quotations', 'Quotations', 'Test Buyers (e2e)'],
    ['quotation', `/sales/quotations/${process.env.E2E_QUOTATION_ID}`, /^Quotation QT\//, 'Mark accepted'],
    ['orders', '/sales/orders', 'Sales orders', 'Test Buyers (e2e)'],
    ['order', `/sales/orders/${process.env.E2E_ORDER_ID}`, /^Sales order SO\//, 'Fulfilled'],
    ['dispatch', `/sales/dispatches/${process.env.E2E_DISPATCH_ID}`, /^Delivery challan DC\//, 'Not generated by this system'],
    ['invoices', '/sales/invoices', 'Invoices', 'Unpaid'],
    ['invoice', `/sales/invoices/${process.env.E2E_INVOICE_ID}`, /^Tax invoice INV\//, 'Tax by HSN/SAC'],
    ['invoice-new', '/sales/invoices/new', 'New invoice', 'Find a customer'],
    ['receivables', '/reports/ageing', 'Outstanding & ageing', 'By customer'],
    ['entity-logo', `/settings/company/${process.env.E2E_ENTITY_ID}`, 'Example Traders Private Limited (test)', 'Upload a logo'],
  ] as const;

test.describe('order-to-cash screens', () => {
  for (const index of pages().keys()) {
    test(`page ${index + 1}: WCAG 2.2 AA, no horizontal scroll, no CSP errors`, async ({ page, problems }, testInfo) => {
      test.setTimeout(AXE_TIMEOUT);
      const [name, path, heading, loaded] = pages()[index] ?? [];
      if (!path || !heading || !loaded) throw new Error('missing page');
      await page.goto(path);
      await expect(page.getByRole('heading', { level: 1, name: heading })).toBeVisible();
      await expect(page.getByText(loaded).filter({ visible: true }).first()).toBeVisible();
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
      expect(overflow, `${name} scrolls sideways`).toBeLessThanOrEqual(0);
      await page.screenshot({ path: `../../test-results/visual/${name}-${testInfo.project.name}.png`, fullPage: true });
      const results = await new AxeBuilder({ page }).withTags(WCAG_TAGS).analyze();
      expect(results.violations.map((v) => `${v.id}: ${v.nodes.map((n) => n.target.join(' ')).join(', ')}`), name).toEqual([]);
      expect(problems).toEqual([]);
    });
  }
});

// The journey downloads two PDFs; downloads go to the run's temporary folder.
test.describe('order-to-cash journey', () => {
  test.use({ acceptDownloads: true });

  test('quotation → order → dispatch → invoice → receivables, in the browser against the real API', async ({ page, problems }, testInfo) => {
    test.skip(testInfo.project.name !== 'desktop-1440', 'changes shared data; one project is enough');
    test.setTimeout(180_000);

    // Quotation: drafted with server-computed totals, then sent (numbered).
    await page.goto('/sales/quotations/new');
    await page.getByRole('combobox', { name: /^Customer/ }).selectOption({ label: 'Test Buyers (e2e)' });
    await page.getByRole('combobox', { name: /^Item 1/ }).selectOption({ label: 'E2E-NUT · Test hex nut (e2e)' });
    await page.getByRole('textbox', { name: /^Quantity 1/ }).fill('4');
    // 4 × 12.50 = 50.00 + 18% = 59.00, computed by the server.
    await expect(page.getByLabel('Totals').getByText('₹59.00')).toBeVisible();
    await page.getByRole('button', { name: 'Save as draft' }).click();
    await expect(page.getByRole('heading', { level: 1, name: 'Quotation (draft)' })).toBeVisible();
    await page.getByRole('button', { name: 'Send (number it)' }).click();
    await expect(page.getByRole('heading', { level: 1, name: /^Quotation QT\/\d\d-\d\d\/0002$/ })).toBeVisible();
    await page.getByRole('button', { name: 'Mark accepted' }).click();
    await page.getByRole('button', { name: 'Convert to sales order' }).click();

    // Order: choose the warehouse, confirm (reserves stock).
    await expect(page.getByRole('heading', { level: 1, name: 'Sales order (draft)' })).toBeVisible();
    await page.getByRole('combobox', { name: /^Warehouse/ }).selectOption({ label: 'MAIN · Main godown (e2e)' });
    await page.getByRole('button', { name: 'Save draft' }).click();
    await expect(page.getByRole('combobox', { name: /^Warehouse/ })).toHaveValue(/[0-9a-f]{24}/);
    await page.getByRole('button', { name: 'Confirm order' }).click();
    await expect(page.getByRole('heading', { level: 1, name: /^Sales order SO\// })).toBeVisible();
    await expect(page.getByText('Confirmed', { exact: true }).first()).toBeVisible();

    // Dispatch: the goods leave the warehouse; the worker prints the delivery challan.
    await page.getByRole('button', { name: 'Create dispatch' }).click();
    await expect(page.getByRole('heading', { level: 1, name: 'Delivery challan (draft)' })).toBeVisible();
    await page.getByRole('textbox', { name: 'Vehicle number' }).fill('MH01AB1234');
    await page.getByRole('button', { name: 'Save draft' }).click();
    await expect(page.getByRole('textbox', { name: 'Vehicle number' })).toHaveValue('MH01AB1234');
    await page.getByRole('button', { name: 'Dispatch now' }).click();
    await expect(page.getByRole('heading', { level: 1, name: /^Delivery challan DC\// })).toBeVisible();
    const challan = page.getByRole('button', { name: 'Download delivery challan (PDF)' });
    await expect(challan).toBeVisible({ timeout: 30_000 });
    const [challanFile] = await Promise.all([page.waitForEvent('download'), challan.click()]);
    expect(challanFile.suggestedFilename()).toMatch(/^DC_\d\d-\d\d_\d{4}\.pdf$/);

    // Invoice from the dispatch: issued, numbered, printed.
    await page.getByRole('button', { name: 'Create invoice' }).click();
    await expect(page.getByRole('heading', { level: 1, name: 'Tax invoice (draft)' })).toBeVisible();
    await expect(page.getByLabel('Totals').getByText('₹59.00')).toBeVisible();
    await page.getByRole('button', { name: 'Issue invoice' }).click();
    const heading = page.getByRole('heading', { level: 1, name: /^Tax invoice INV\// });
    await expect(heading).toBeVisible();
    const number = ((await heading.textContent()) ?? '').replace('Tax invoice ', '');
    const pdf = page.getByRole('button', { name: 'Download tax invoice (PDF)' });
    await expect(pdf).toBeVisible({ timeout: 30_000 });
    const [invoiceFile] = await Promise.all([page.waitForEvent('download'), pdf.click()]);
    expect(invoiceFile.suggestedFilename()).toMatch(/^INV_\d\d-\d\d_\d{4}\.pdf$/);

    // Receivables show it, and the stock records still agree.
    await page.goto('/reports/ageing');
    await expect(page.getByRole('link', { name: number }).first()).toBeVisible();
    await page.goto('/inventory/stock');
    await page.getByRole('tab', { name: 'Check records' }).click();
    await page.getByRole('button', { name: 'Run the check' }).click();
    await expect(page.getByRole('status').filter({ hasText: /^All \d+ balances and \d+ valuations agree with the ledger/ })).toBeVisible();
    expect(problems).toEqual([]);
  });
});
