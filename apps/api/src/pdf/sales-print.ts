import { stateName } from '@bizmgmt/contracts';
import { amountInWords, dec, formatQty } from '@bizmgmt/domain';
import type { AddressDoc, SalesDocDoc } from '../models.js';
import { DELIVERY_CHALLAN_TEMPLATE, QUOTATION_TEMPLATE, SALES_INVOICE_TEMPLATE, type SalesPrint, type SalesPrintParty } from './templates/sales.js';

/** Indian digit grouping without Intl (output must not depend on the ICU build): 1234567.5 → "12,34,567.50". */
export function inr(amount: string): string {
  const d = dec(amount);
  const [whole = '0', paise = '00'] = d.abs().toFixed(2).split('.');
  const last3 = whole.slice(-3);
  const rest = whole.slice(0, -3);
  const grouped = rest ? `${rest.replace(/\B(?=(\d{2})+(?!\d))/g, ',')},${last3}` : last3;
  return `${d.isNegative() && !d.isZero() ? '−' : ''}${grouped}.${paise}`;
}

/** Unit prices keep up to 6 decimals (financial-policy §1): 2 when that is exact, otherwise the digits that matter. */
function price(value: string): string {
  const d = dec(value);
  if (d.decimalPlaces() <= 2) return inr(value);
  const [whole = '0', fraction = ''] = d.toFixed().split('.');
  return `${inr(whole).slice(0, -3)}.${fraction}`;
}

const ddmmyyyy = (d: string) => `${d.slice(8, 10)}-${d.slice(5, 7)}-${d.slice(0, 4)}`;
const state = (code: string | null) => (code ? `${stateName(code) ?? code} (${code})` : null);
const addressText = (a: AddressDoc | null) => (a ? [a.line1, a.line2, a.city, a.district, `${stateName(a.stateCode) ?? a.stateCode} ${a.pincode}`].filter(Boolean).join(', ') : null);
const rate = (r: string) => `${dec(r).toString()}%`;

/** Which template a sales document prints with. */
export function templateFor(doc: Pick<SalesDocDoc, 'docType'>): string {
  return doc.docType === 'sales_invoice' ? SALES_INVOICE_TEMPLATE : doc.docType === 'dispatch' ? DELIVERY_CHALLAN_TEMPLATE : QUOTATION_TEMPLATE;
}

const TITLES: Record<SalesDocDoc['documentKind'], string> = {
  quotation: 'Quotation',
  proforma_invoice: 'Proforma invoice',
  sales_order: 'Sales order',
  delivery_challan: 'Delivery challan',
  tax_invoice: 'Tax invoice',
  bill_of_supply: 'Bill of supply',
};

/**
 * The printed form of a numbered sales document, from its snapshot only.
 * `logo` is the logo file frozen on the document (null when it had none).
 */
export function salesPrint(doc: SalesDocDoc, logo: { dataUrl: string } | null, options: { einvoiceApplicable: boolean }): SalesPrint {
  if (!doc.number) throw new Error('Only numbered documents are printed');
  const s = doc.seller;
  const b = doc.buyer;
  const isInvoice = doc.docType === 'sales_invoice';
  const isChallan = doc.docType === 'dispatch';
  const isEstimate = doc.docType === 'quotation';
  const taxColumns = doc.documentKind !== 'bill_of_supply';
  const utgst = doc.lines.some((l) => !dec(l.amounts.utgst.toString()).isZero());
  const sameAddress = JSON.stringify(b.billingAddress) === JSON.stringify(b.shippingAddress);
  const buyerParty = (address: AddressDoc | null): SalesPrintParty => ({ name: b.name, legalName: b.legalName, gstin: b.gstin, address: addressText(address), state: state(address?.stateCode ?? b.stateCode) });
  const t = doc.totals;
  const m = (v: { toString(): string }) => inr(v.toString());
  const nonZero = (v: { toString(): string }) => !dec(v.toString()).isZero();

  const totals: Array<[string, string]> = [['Gross value', m(t.gross)]];
  if (nonZero(t.discount)) totals.push(['Discount', `−${m(t.discount)}`]);
  totals.push(['Taxable value', m(t.taxable)]);
  if (taxColumns) {
    if (nonZero(t.cgst)) totals.push(['CGST', m(t.cgst)]);
    if (nonZero(t.sgst)) totals.push(['SGST', m(t.sgst)]);
    if (nonZero(t.utgst)) totals.push(['UTGST', m(t.utgst)]);
    if (nonZero(t.igst)) totals.push(['IGST', m(t.igst)]);
    if (nonZero(t.cess)) totals.push(['Cess', m(t.cess)]);
    if (nonZero(t.reverseChargeTax)) totals.push(['Tax payable by the recipient (reverse charge, not included)', m(t.reverseChargeTax)]);
  }
  if (nonZero(t.roundOff)) totals.push(['Round off', m(t.roundOff)]);

  const facts: Array<[string, string]> = [];
  if (doc.validUntil) facts.push(['Valid until', ddmmyyyy(doc.validUntil)]);
  if (isInvoice && doc.dueDate) facts.push(['Due date', ddmmyyyy(doc.dueDate)]);
  if (doc.customerReference) facts.push(['Your reference', doc.customerReference]);
  if (isChallan) {
    facts.push(['Reason for transport', 'Supply']);
    if (doc.transport?.vehicleNumber) facts.push(['Vehicle', doc.transport.vehicleNumber]);
    if (doc.transport?.transporterName) facts.push(['Transporter', doc.transport.transporterName]);
    facts.push(['E-way bill', doc.transport?.ewayBillNumber ? `${doc.transport.ewayBillNumber} (recorded; not generated by this system)` : 'Not generated by this system']);
  }

  const declarations: string[] = [];
  if (isEstimate) declarations.push('This is not a tax invoice. Tax shown is an estimate at today’s rates; the tax invoice will show the tax charged.');
  if (isInvoice && doc.documentKind === 'bill_of_supply' && s.registrationType === 'composition') declarations.push('Composition taxable person, not eligible to collect tax on supplies.');
  if (isChallan) declarations.push('Delivery challan for the movement of goods (Rule 55). This is not a tax invoice.');

  const bank = doc.bankAccount ? [doc.bankAccount.bankName, doc.bankAccount.accountName, `A/c ${doc.bankAccount.accountNumber}`, `IFSC ${doc.bankAccount.ifsc}`, doc.bankAccount.branch, doc.bankAccount.upiId ? `UPI ${doc.bankAccount.upiId}` : ''].filter(Boolean).join(' · ') : null;
  const anyGoods = doc.lines.some((l) => l.item.type !== 'service');

  return {
    title: TITLES[doc.documentKind],
    number: doc.number,
    docDate: ddmmyyyy(doc.docDate),
    facts,
    seller: { legalName: s.legalName, tradeName: s.tradeName, gstin: s.gstin, pan: s.pan, address: addressText(s.address) ?? '', state: state(s.stateCode) ?? '', contact: [s.phone, s.email].filter(Boolean).join(' · ') },
    logo,
    billTo: buyerParty(b.billingAddress),
    shipTo: sameAddress || !b.shippingAddress ? null : buyerParty(b.shippingAddress),
    placeOfSupply: state(doc.placeOfSupply) ?? doc.placeOfSupply,
    supply: doc.supply,
    stateTaxLabel: utgst ? 'UTGST' : 'SGST',
    reverseCharge: isEstimate || doc.documentKind === 'bill_of_supply' ? null : doc.lines.some((l) => l.reverseCharge) ? 'Yes' : 'No',
    taxColumns,
    lines: doc.lines.map((l) => ({
      name: l.item.name,
      sku: l.item.sku,
      hsnSac: l.item.hsnSac,
      qty: formatQty(l.qty.toString(), l.item.decimals),
      uqc: l.item.uqc,
      unitPrice: price(l.unitPrice.toString()),
      discount: nonZero(l.amounts.discount) || nonZero(l.amounts.documentDiscount) ? inr(dec(l.amounts.discount.toString()).plus(dec(l.amounts.documentDiscount.toString())).toString()) : '—',
      taxable: m(l.amounts.taxable),
      taxRate: l.taxRate ? rate(l.taxRate.toString()) : null,
      cgst: m(l.amounts.cgst),
      sgst: m(dec(l.amounts.sgst.toString()).plus(dec(l.amounts.utgst.toString())).toString()),
      igst: m(l.amounts.igst),
      cess: m(l.amounts.cess),
      total: m(l.amounts.total),
      reverseCharge: l.reverseCharge,
    })),
    totals,
    grand: `₹${m(t.grand)}`,
    amountInWords: amountInWords(t.grand.toString()),
    hsnSummary: doc.hsnSummary.map((r) => {
      const tax = dec(r.cgst.toString()).plus(dec(r.sgst.toString())).plus(dec(r.utgst.toString())).plus(dec(r.igst.toString())).plus(dec(r.cess.toString()));
      return { hsnSac: r.hsnSac, taxable: m(r.taxable), rate: r.rate ? rate(r.rate.toString()) : '—', cgst: m(r.cgst), sgst: m(dec(r.sgst.toString()).plus(dec(r.utgst.toString())).toString()), igst: m(r.igst), cess: m(r.cess), tax: inr(tax.toString()) };
    }),
    bank: isChallan ? null : bank,
    notes: doc.notes,
    terms: doc.terms,
    declarations,
    // Rule 48: goods in triplicate, services in duplicate; Rule 55 challans in triplicate.
    copies: isEstimate ? ['Copy for the customer'] : isChallan ? ['Original for consignee', 'Duplicate for transporter', 'Triplicate for consignor'] : anyGoods ? ['Original for recipient', 'Duplicate for transporter', 'Triplicate for supplier'] : ['Original for recipient', 'Duplicate for supplier'],
    footer: isInvoice && options.einvoiceApplicable ? 'Computer-generated document. Not an e-invoice: no IRN has been obtained for it by this system.' : 'Computer-generated document.',
    signatory: 'Authorised signatory',
  };
}
